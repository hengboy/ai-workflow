import { randomUUID } from 'node:crypto';
import { chmod, mkdir, open, readFile, readdir, rm } from 'node:fs/promises';
import { hostname } from 'node:os';
import { join } from 'node:path';
import type { ExecutionConfig } from './config.js';
import { DEFAULT_EXECUTION_CONFIG } from './config.js';
import type { ExecutionPaths } from './paths.js';
import type { ExecutionCheckpoint, ExecutionEvent, ExecutionLock, ExecutionRun } from './types.js';
import { assertExecutionRecord, validateExecutionRecord } from './validate.js';
import { appendFsync, atomicWrite, syncDirectory } from '../utils/fs.js';

/** Raised when telemetry bytes cannot be recorded, so callers can warn and continue. */
export class ExecutionTelemetryError extends Error {
  constructor(message: string, options?: ErrorOptions) {
    super(message, options);
    this.name = 'ExecutionTelemetryError';
  }
}

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function isMissing(error: unknown): boolean {
  return (error as NodeJS.ErrnoException | undefined)?.code === 'ENOENT';
}

/** Create the owner-only execution and checkpoint directories. */
export async function ensureExecutionPaths(paths: ExecutionPaths): Promise<void> {
  for (const directory of [paths.directory, paths.checkpoints]) {
    await mkdir(directory, { recursive: true, mode: 0o700 });
    await chmod(directory, 0o700);
  }
}

/** Atomically persist the single run document after validating its shape. */
export async function writeRun(paths: ExecutionPaths, run: ExecutionRun): Promise<ExecutionRun> {
  assertExecutionRecord('run', run, paths.run);
  await ensureExecutionPaths(paths);
  await atomicWrite(paths.run, `${JSON.stringify(run, null, 2)}\n`);
  return run;
}

/** Read and validate the run document, rejecting corrupt or malformed content. */
export async function readRun(paths: ExecutionPaths): Promise<ExecutionRun> {
  const parsed = JSON.parse(await readFile(paths.run, 'utf8')) as unknown;
  assertExecutionRecord('run', parsed, paths.run);
  return parsed as ExecutionRun;
}

/** Caller-supplied event fields; identity and timestamp are generated by the store. */
export interface ExecutionEventInput {
  run_id: string;
  plan_id: string;
  type: ExecutionEvent['type'];
  task_id?: string;
  invocation_id?: string;
  payload?: Record<string, unknown>;
}

/** True when an existing stream lacks a terminating newline on its final line. */
async function needsLeadingNewline(path: string): Promise<boolean> {
  let handle: Awaited<ReturnType<typeof open>> | undefined;
  try {
    handle = await open(path, 'r');
    const info = await handle.stat();
    if (info.size === 0) return false;
    const buffer = Buffer.alloc(1);
    await handle.read(buffer, 0, 1, info.size - 1);
    return (buffer[0] ?? 0) !== 0x0a;
  } catch (error) {
    if (isMissing(error)) return false;
    throw error;
  } finally {
    if (handle) await handle.close();
  }
}

/**
 * Append one generated event as a single fsynced JSONL line. Oversized or invalid
 * telemetry is refused before any file is touched so existing bytes stay intact.
 */
export async function appendEvent(
  paths: ExecutionPaths,
  input: ExecutionEventInput,
  config: ExecutionConfig = DEFAULT_EXECUTION_CONFIG,
): Promise<ExecutionEvent> {
  const event: ExecutionEvent = {
    event_id: randomUUID(),
    run_id: input.run_id,
    plan_id: input.plan_id,
    type: input.type,
    timestamp: new Date().toISOString(),
  };
  if (input.task_id !== undefined) event.task_id = input.task_id;
  if (input.invocation_id !== undefined) event.invocation_id = input.invocation_id;
  if (input.payload !== undefined) event.payload = input.payload;

  const validation = validateExecutionRecord('event', event);
  if (!validation.valid) throw new ExecutionTelemetryError(`Invalid execution event: ${validation.errors.join('; ')}`);

  let serialized: string;
  try {
    serialized = JSON.stringify(event);
  } catch (error) {
    throw new ExecutionTelemetryError(`Unable to serialize execution event: ${errorMessage(error)}`, { cause: error });
  }
  if (Buffer.byteLength(serialized, 'utf8') > config.maxEventLineBytes) {
    throw new ExecutionTelemetryError(
      `Execution event line exceeds the ${config.maxEventLineBytes}-byte limit`,
    );
  }

  try {
    await ensureExecutionPaths(paths);
    const prefix = (await needsLeadingNewline(paths.events)) ? '\n' : '';
    await appendFsync(paths.events, `${prefix}${serialized}\n`);
  } catch (error) {
    throw new ExecutionTelemetryError(`Failed to append execution event: ${errorMessage(error)}`, { cause: error });
  }
  return event;
}

/** Options bounding how many of the newest events are returned. */
export interface ReadEventsOptions {
  limit?: number;
}

/** Parsed events plus any corrupt or unterminated line warnings and truncation state. */
export interface EventReadResult {
  events: ExecutionEvent[];
  warnings: string[];
  truncated: boolean;
}

/** Read the event stream in order, skipping and reporting unterminated or malformed lines. */
export async function readEvents(
  paths: ExecutionPaths,
  options: ReadEventsOptions = {},
): Promise<EventReadResult> {
  let source: string;
  try {
    source = await readFile(paths.events, 'utf8');
  } catch (error) {
    if (isMissing(error)) return { events: [], warnings: [], truncated: false };
    throw error;
  }
  if (source.length === 0) return { events: [], warnings: [], truncated: false };

  const terminated = source.endsWith('\n');
  const segments = source.split('\n');
  const lines = terminated ? segments.slice(0, -1) : segments;
  const warnings: string[] = [];
  const events: ExecutionEvent[] = [];

  lines.forEach((line, index) => {
    const lineNumber = index + 1;
    if (!terminated && index === lines.length - 1) {
      warnings.push(`event stream line ${lineNumber} is unterminated and was ignored`);
      return;
    }
    let parsed: unknown;
    try {
      parsed = JSON.parse(line);
    } catch {
      warnings.push(`event stream line ${lineNumber} is malformed and was ignored`);
      return;
    }
    const validation = validateExecutionRecord('event', parsed);
    if (!validation.valid) {
      warnings.push(`event stream line ${lineNumber} is invalid: ${validation.errors.join('; ')}`);
      return;
    }
    events.push(parsed as ExecutionEvent);
  });

  const limit = options.limit;
  if (typeof limit === 'number' && Number.isInteger(limit) && limit >= 0 && events.length > limit) {
    return { events: events.slice(events.length - limit), warnings, truncated: true };
  }
  return { events, warnings, truncated: false };
}

/** Build a lexicographically sortable, filesystem-safe checkpoint file name. */
function checkpointFileName(checkpoint: ExecutionCheckpoint): string {
  const stamp = checkpoint.created_at.replace(/[:.]/g, '-');
  const safeId = checkpoint.checkpoint_id.replace(/[^A-Za-z0-9._-]/g, '_');
  return `${stamp}__${safeId}.json`;
}

/** Atomically persist a checkpoint and prune the oldest files beyond the retention limit. */
export async function writeCheckpoint(
  paths: ExecutionPaths,
  checkpoint: ExecutionCheckpoint,
  config: ExecutionConfig = DEFAULT_EXECUTION_CONFIG,
): Promise<ExecutionCheckpoint> {
  const target = join(paths.checkpoints, checkpointFileName(checkpoint));
  assertExecutionRecord('checkpoint', checkpoint, target);
  await ensureExecutionPaths(paths);
  await atomicWrite(target, `${JSON.stringify(checkpoint, null, 2)}\n`);

  const names = (await readdir(paths.checkpoints)).filter((name) => name.endsWith('.json')).sort();
  const retention = Math.max(1, Math.trunc(config.checkpointHistory));
  const excess = names.length - retention;
  for (let index = 0; index < excess; index += 1) {
    const name = names[index];
    if (name) await rm(join(paths.checkpoints, name), { force: true });
  }
  return checkpoint;
}

/** Checkpoint recovery state: absent, the newest valid record, or manual recovery. */
export type CheckpointReadResult =
  | { status: 'absent'; warnings: string[] }
  | { status: 'ok'; checkpoint: ExecutionCheckpoint; warnings: string[] }
  | { status: 'manual'; warnings: string[] };

/** Read the newest valid checkpoint, falling back past corrupt files. */
export async function readLatestCheckpoint(paths: ExecutionPaths): Promise<CheckpointReadResult> {
  let names: string[];
  try {
    names = (await readdir(paths.checkpoints)).filter((name) => name.endsWith('.json'));
  } catch (error) {
    if (isMissing(error)) return { status: 'absent', warnings: [] };
    throw error;
  }
  if (names.length === 0) return { status: 'absent', warnings: [] };

  names.sort().reverse();
  const warnings: string[] = [];
  for (const name of names) {
    const path = join(paths.checkpoints, name);
    let parsed: unknown;
    try {
      parsed = JSON.parse(await readFile(path, 'utf8'));
    } catch (error) {
      warnings.push(`checkpoint ${name} is unreadable: ${errorMessage(error)}`);
      continue;
    }
    const validation = validateExecutionRecord('checkpoint', parsed);
    if (!validation.valid) {
      warnings.push(`checkpoint ${name} is invalid: ${validation.errors.join('; ')}`);
      continue;
    }
    return { status: 'ok', checkpoint: parsed as ExecutionCheckpoint, warnings };
  }
  return { status: 'manual', warnings };
}

/** Caller-supplied lock identity; absent fields receive sensible local defaults. */
export interface LockRequest {
  command: string;
  owner_id?: string;
  host?: string;
  pid?: number;
  acquired_at?: string;
}

/** Current-host and liveness hooks used while checking an existing lock. */
export interface LockOptions {
  host?: string;
  isAlive?: (pid: number) => boolean;
}

/** Lock acquisition outcome: acquired with the stored record, or a refusal reason. */
export type LockAcquisition =
  | { acquired: true; recovered: boolean; lock: ExecutionLock }
  | { acquired: false; reason: 'live' | 'other-host' | 'unreadable' };

/** Read the lock record, returning undefined when no lock file exists. */
export async function readLock(paths: ExecutionPaths): Promise<ExecutionLock | undefined> {
  let source: string;
  try {
    source = await readFile(paths.lock, 'utf8');
  } catch (error) {
    if (isMissing(error)) return undefined;
    throw error;
  }
  const parsed = JSON.parse(source) as unknown;
  assertExecutionRecord('lock', parsed, paths.lock);
  return parsed as ExecutionLock;
}

/** Default liveness probe: signal 0 succeeds while the process exists. */
export function isProcessAlive(pid: number): boolean {
  if (!Number.isInteger(pid) || pid <= 0) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return (error as NodeJS.ErrnoException).code === 'EPERM';
  }
}

/** Create the lock file exclusively; false means another writer won the race. */
async function createLockFile(paths: ExecutionPaths, lock: ExecutionLock): Promise<boolean> {
  let handle: Awaited<ReturnType<typeof open>> | undefined;
  try {
    handle = await open(paths.lock, 'wx', 0o600);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'EEXIST') return false;
    throw error;
  }
  if (!handle) return false;
  try {
    await handle.writeFile(`${JSON.stringify(lock, null, 2)}\n`);
    await handle.sync();
  } finally {
    await handle.close();
  }
  await chmod(paths.lock, 0o600);
  await syncDirectory(paths.directory);
  return true;
}

/**
 * Acquire the single-writer lock. A same-host lock whose process is gone is
 * recovered; a live lock, another host's lock, or unreadable bytes are refused.
 */
export async function acquireLock(
  paths: ExecutionPaths,
  request: LockRequest,
  options: LockOptions = {},
): Promise<LockAcquisition> {
  await ensureExecutionPaths(paths);
  const currentHost = options.host ?? hostname();
  const alive = options.isAlive ?? isProcessAlive;

  for (let attempt = 0; attempt < 5; attempt += 1) {
    let existing: ExecutionLock | undefined;
    try {
      existing = await readLock(paths);
    } catch {
      return { acquired: false, reason: 'unreadable' };
    }

    let recovered = false;
    if (existing) {
      if (existing.host !== currentHost) return { acquired: false, reason: 'other-host' };
      if (alive(existing.pid)) return { acquired: false, reason: 'live' };
      recovered = true;
      try {
        await rm(paths.lock, { force: true });
      } catch {
        // Another writer may have replaced it; re-read and decide again.
      }
    }

    const lock: ExecutionLock = {
      owner_id: request.owner_id ?? randomUUID(),
      pid: request.pid ?? process.pid,
      host: request.host ?? currentHost,
      acquired_at: request.acquired_at ?? new Date().toISOString(),
      command: request.command,
    };
    assertExecutionRecord('lock', lock, paths.lock);
    if (await createLockFile(paths, lock)) return { acquired: true, recovered, lock };
  }
  return { acquired: false, reason: 'live' };
}

/** Release the lock, returning whether a lock file was actually removed. */
export async function releaseLock(paths: ExecutionPaths): Promise<boolean> {
  try {
    await rm(paths.lock);
    return true;
  } catch (error) {
    if (isMissing(error)) return false;
    throw error;
  }
}
